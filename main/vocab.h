inline void print_token(int id) {
    if (id < 0 || id >= 2048) return;
    const char* str = VOCAB_TABLE[id];
    int len = strlen(str);
    if (len > 0 && str[0] == '<' && str[len - 1] == '>') {
        if (strcmp(str, "<0x0A>") == 0) Serial.println();
        return;
    }
    Serial.print(str);
}

inline bool is_stop_token(int id) {
    if (id <= 2) return true; // <unk>, <s>, </s>
    if (id == 281) return true; // 'User'
    return false;
}

inline int tokenize_prompt(const char* text, int* tokens_out, int max_tokens) {
    int count = 0;
    String s = text;
    int len = s.length();
    int i = 0;
    while (i < len && count < max_tokens) {
        int best_id = -1;
        int best_len = 0;
        for (int tid = 4; tid < 2048; tid++) {
            const char* v = VOCAB_TABLE[tid];
            int vlen = strlen(v);
            if (vlen > 0 && v[0] == '<' && v[vlen - 1] == '>') continue;
            if (vlen > best_len && vlen <= (len - i)) {
                if (strncmp(s.c_str() + i, v, vlen) == 0) {
                    best_id = tid;
                    best_len = vlen;
                }
            }
        }
        if (best_len > 0) {
            tokens_out[count++] = best_id;
            i += best_len;
        } else {
            // Check byte fallback (<0x..>)
            uint8_t byte_val = (uint8_t)s[i];
            tokens_out[count++] = 3 + byte_val;
            i++;
        }
    }
    return count;
}


